//单调栈: 求每个元素左右第一个更大/更小的位置, O(n)
//需预定义: int stk[N], top = 0;  a[1..n]
//场景: 柱状图最大矩形、接雨水、贡献法(统计元素作为极值的子区间个数)

//右侧第一个比 a[i] 大的位置(不存在记 n + 1): 维护栈内单调递减(存下标)
void get_nxt_bigger() {
    top = 0;
    for(int i = 1; i <= n; i++) {
        while(top && a[stk[top]] < a[i]) {
            nxt_bigger[stk[top]] = i;
            top--;
        }
        stk[++top] = i;
    }
    while(top) {                            //栈内剩余元素右侧没有更大的
        nxt_bigger[stk[top]] = n + 1;
        top--;
    }
}
//右侧第一个更小: 把 < 改成 >;  左侧第一个更大/更小: 倒着扫一遍

