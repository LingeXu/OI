//曼哈顿距离 <=> 切比雪夫距离 的坐标变换(45° 旋转)

//曼哈顿 d = |x1-x2| + |y1-y2|
//变换 (x, y) -> (u, v) = (x+y, x-y) 后, 曼哈顿距离 = 切比雪夫距离 max(|u1-u2|, |v1-v2|)
//切比雪夫 d = max(|x1-x2|, |y1-y2|)
//变换 (x, y) -> ((x+y)/2, (x-y)/2) 后, 切比雪夫距离 = 曼哈顿距离

//用途:
//1. "到某点曼哈顿距离 <= k 的点数": 菱形很难数 -> 旋转后是正方形, 二维前缀和 O(1)
//2. "与若干点曼哈顿距离的最大值最小": 旋转后只需维护 u, v 的最大最小值, 不用二分图/最优解搜索
//3. "n 个点两两切比雪夫距离最大值": 直接 max(maxu-minu, maxv-minv)
//注意: 变换后坐标可能为半整数/负值, 离散化或整体平移处理
